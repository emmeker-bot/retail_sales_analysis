-- ---------------------------------------------------------------------
-- PART A: AGGREGATE FUNCTIONS
-- ---------------------------------------------------------------------

-- Question 1: Total revenue generated by the company
SELECT
    SUM(sales_amount) AS total_revenue
FROM sales;

-- Question 2: Total number of sales transactions

SELECT
    COUNT(*) AS total_transactions
FROM sales;

-- Question 3: Average sales amount per transaction
SELECT
    AVG(sales_amount) AS average_transaction
FROM sales;

-- Question 4: Highest and lowest sales amounts
SELECT
    MAX(sales_amount) AS highest_sales_amount,
    MIN(sales_amount) AS lowest_sales_amount
FROM sales;

-- ---------------------------------------------------------------------
-- PART B: GROUP BY
-- ---------------------------------------------------------------------

-- Question 5: Total sales by region, highest to lowest
SELECT
    region,
    SUM(sales_amount) AS total_sales
FROM sales
GROUP BY region
ORDER BY total_sales DESC;

-- Question 6: Total sales by product
SELECT
    product,
    SUM(sales_amount) AS total_sales
FROM sales
GROUP BY product;

-- Question 7: Number of transactions by sales representative
SELECT
    sales_rep,
    COUNT(*) AS total_transactions
FROM sales
GROUP BY sales_rep;

-- Question 8: Average transaction amount by region
SELECT
    region,
    AVG(sales_amount) AS average_transaction
FROM sales
GROUP BY region;

-- Question 9: Total sales for every region and product combination
SELECT
    region,
    product,
    SUM(sales_amount) AS total_sales
FROM sales
GROUP BY region, product;

-- ---------------------------------------------------------------------
-- PART C: HAVING
-- ---------------------------------------------------------------------

-- Question 10: Regions with total sales greater than 1,000,000
SELECT
    region,
    SUM(sales_amount) AS total_sales
FROM sales
GROUP BY region
HAVING SUM(sales_amount) > 1000000;

-- Question 11: Products with average transaction amount greater than 500,000
SELECT
    product,
    AVG(sales_amount) AS average_sales
FROM sales
GROUP BY product
HAVING AVG(sales_amount) > 500000;

-- ---------------------------------------------------------------------
-- PART D: STRING FUNCTIONS
-- ---------------------------------------------------------------------

-- Question 12: Sales representatives names in uppercase
SELECT
    sales_rep,
    UPPER(sales_rep) AS uppercase_name
FROM sales;

-- Question 13: Product names in lowercase
SELECT
    product,
    LOWER(product) AS lowercase_product
FROM sales;

-- Question 14: Combine sales representative and region
SELECT
    sales_rep,
    region,
    CONCAT(sales_rep, ' - ', region) AS rep_location
FROM sales;

-- Question 15: Product name and number of characters
SELECT
    product,
    LENGTH(product) AS product_name_length
FROM sales;

-- ---------------------------------------------------------------------
-- PART E: DATE FUNCTIONS
-- ---------------------------------------------------------------------

-- Question 16: Extract year and month from sale_date
SELECT
    EXTRACT(YEAR FROM sale_date) AS sale_year,
    EXTRACT(MONTH FROM sale_date) AS sale_month
FROM sales;

-- Question 17: Total sales by month

SELECT
    EXTRACT(MONTH FROM sale_date) AS sale_month,
    TO_CHAR(sale_date, 'MONTH') AS sale_month_name,
	SUM(sales_amount) AS total_sales
FROM sales
GROUP BY 
    EXTRACT(MONTH FROM sale_date),
    TO_CHAR(sale_date, 'MONTH')      
ORDER BY 
    sale_month;

-- Question 18: Number of transactions by month
	
SELECT
    TO_CHAR(DATE_TRUNC('MONTH', sale_date), 'Month') AS sale_month,
    COUNT(*) AS total_transactions
FROM sales
GROUP BY DATE_TRUNC('MONTH', sale_date)
ORDER BY DATE_TRUNC('MONTH', sale_date);


-- ---------------------------------------------------------------------
-- PART F: CASE STATEMENTS
-- ---------------------------------------------------------------------

-- Question 19: Classify each transaction by value
SELECT
    product,
    sales_amount,
    CASE
        WHEN sales_amount >= 1000000 THEN 'High Value'
        WHEN sales_amount >= 500000 THEN 'Medium Value'
        ELSE 'Low Value'
    END AS transaction_category
FROM sales;

-- Question 20: Classify customers
SELECT
    customer_type,
    CASE customer_type
        WHEN 'Corporate' THEN 'Business Customer'
        WHEN 'Individual' THEN 'Retail Customer'
    END AS customer_group
FROM sales;

-- ---------------------------------------------------------------------
-- PART G: CASE + AGGREGATE FUNCTIONS
-- ---------------------------------------------------------------------

-- Question 23: Total revenue from Corporate customers
SELECT
    SUM(
        CASE
            WHEN customer_type = 'Corporate' THEN sales_amount
            ELSE 0
        END
    ) AS corporate_revenue
FROM sales;

-- Question 24: Corporate and Individual revenue
SELECT
    SUM(
        CASE
            WHEN customer_type = 'Corporate' THEN sales_amount
            ELSE 0
        END
    ) AS corporate_revenue,
    SUM(
        CASE
            WHEN customer_type = 'Individual' THEN sales_amount
            ELSE 0
        END
    ) AS individual_revenue
FROM sales;

-- Question 25: Number of High Value transactions by region
SELECT
    region,
    COUNT(
        CASE
            WHEN sales_amount >= 1000000 THEN 1
        END
    ) AS high_value_transactions
FROM sales
GROUP BY region;

-- ---------------------------------------------------------------------
-- PART H: BUSINESS ANALYSIS CHALLENGE
-- ---------------------------------------------------------------------

-- Regional performance report
SELECT
    region,
    SUM(sales_amount) AS total_revenue,
    COUNT(*) AS number_of_transactions,
    AVG(sales_amount) AS average_transaction,
    SUM(
        CASE
            WHEN customer_type = 'Corporate' THEN sales_amount
            ELSE 0
        END
    ) AS corporate_revenue,
    SUM(
        CASE
            WHEN customer_type = 'Individual' THEN sales_amount
            ELSE 0
        END
    ) AS individual_revenue
FROM sales
GROUP BY region
ORDER BY total_revenue DESC;

-- ---------------------------------------------------------------------
-- FINAL ANALYSIS SUPPORT QUERIES
-- ---------------------------------------------------------------------

-- Region with highest and lowest revenue
SELECT
    region,
    SUM(sales_amount) AS total_revenue
FROM sales
GROUP BY region
ORDER BY total_revenue DESC;

-- Product with highest revenue
SELECT
    product,
    SUM(sales_amount) AS total_revenue
FROM sales
GROUP BY product
ORDER BY total_revenue DESC;

-- Sales representative with the highest number of transactions
SELECT
    sales_rep,
    COUNT(*) AS total_transactions
FROM sales
GROUP BY sales_rep
ORDER BY total_transactions DESC;

-- Revenue by customer type
SELECT
    customer_type,
    SUM(sales_amount) AS total_revenue
FROM sales
GROUP BY customer_type
ORDER BY total_revenue DESC;

-- Monthly Sales Performance

SELECT
    DATE_TRUNC('MONTH', sale_date) AS sale_month,
	COUNT(sale_id) AS total_orders,
    SUM(sales_amount) AS total_sales,
	ROUND(AVG(sales_amount), 2) AS average_order_value
FROM sales
GROUP BY DATE_TRUNC('MONTH', sale_date)
ORDER BY total_sales DESC;

-- Total High Value transactions
SELECT
    COUNT(*) AS high_value_transactions
FROM sales
WHERE sales_amount >= 1000000;























