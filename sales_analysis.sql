DROP TABLE IF EXISTS sales;

CREATE TABLE sales (
    sale_id INT PRIMARY KEY,
    product VARCHAR(50),
    category VARCHAR(50),
    region VARCHAR(50),
    sales_rep VARCHAR(50),
    quantity INT,
    unit_price DECIMAL(12,2),
    sales_amount DECIMAL(12,2),
    sale_date DATE,
    customer_type VARCHAR(50)
);

